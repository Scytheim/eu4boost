"""The game's random generator in Python, written from the instructions of FUN_1414c6f50 (seeding) and
FUN_1414c71b0 (a draw), independently of src/rng.c: python tools/analysis/rng_oracle.py > src/rng_oracle.inc
For every seed and count: CRC-32 of the 625 words (little endian, the index last) after `count` draws from the
seed, and of the next 1,300 draws. The test build (eb_test_rng) checks its two C ways against this table."""
import struct, zlib

M = 0xffffffff


def sar(x, k):                     # arithmetic shift right of a 32-bit value
    x &= M
    return ((x - (1 << 32)) >> k) & M if x & 0x80000000 else x >> k


def seed(v):                       # 0x1414c6f50: s[0] = seed, s[i] = (sar(s[i-1], 30) ^ s[i-1]) * 0x6c078965 + i
    s = [v & M] + [0] * 624
    for i in range(1, 624):
        s[i] = ((sar(s[i - 1], 30) ^ s[i - 1]) * 0x6c078965 + i) & M
    s[624] = 0
    return s


def draw(s):                       # 0x1414c71b0
    idx = s[624]
    if idx == 0:
        for i in range(624):
            y = ((s[i] ^ s[(i + 1) % 624]) & 0x7fffffff) ^ s[i]   # btr ecx, 31; xor ecx, [r9]
            v = sar(y, 1) ^ s[(i + 397) % 624]                    # sar edx, 1; xor edx, [rbx + rax*4]
            r = y & 0x80000001                                    # and ecx, 0x80000001; jge
            if r & 0x80000000:
                r = (((r - 1) & M) | 0xfffffffe) + 1 & M          # dec; or 0xfffffffe; inc
            s[i] = v ^ 0x9908b0df if r == 1 else v
    x = s[idx]
    x ^= sar(x, 11)
    x ^= (x & 0xff3a58ad) << 7 & M
    x ^= (x & 0xffffdf8c) << 15 & M
    s[624] = (idx + 1) % 624
    return (sar(x, 18) ^ x) & M


SEEDS = [0, 1, 1234, 0x80000000, 0x80000001, 0xffffffff, 0x7fffffff, 0xdeadbeef]
COUNTS = [0, 1, 2, 623, 624, 625, 1247, 1248, 1249, 1872, 6241, 100003]
print('// generated by tools/analysis/rng_oracle.py: { seed, draws, CRC-32 of the state after them, of the next 1,300 draws }')
for sd in SEEDS:
    for n in COUNTS:
        s = seed(sd)
        for _ in range(n):
            draw(s)
        cs = zlib.crc32(struct.pack('<625I', *s))
        nx = [draw(s) for _ in range(1300)]
        cn = zlib.crc32(struct.pack('<1300I', *nx))
        print(f'    {{ 0x{sd:08x}u, {n}u, 0x{cs:08x}u, 0x{cn:08x}u }},')
